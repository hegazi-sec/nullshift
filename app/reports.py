"""Incident report builders.

Renders a case (incident + linked conversations + IOC verdict trail) as a
shareable document. Two formats:

- Markdown: for pasting into tickets (TheHive, Jira, email).
- HTML: self-contained, print-optimized page — the analyst uses the browser's
  Print → Save as PDF for a hand-off artifact. No PDF library dependency.

All user/LLM content is escaped; assistant replies are rendered as
preformatted text rather than re-interpreting their markdown, so nothing in a
chat can inject markup into the report.
"""
from __future__ import annotations

import html
from datetime import datetime, timezone
from typing import Any, Dict, List, Optional


def _fmt_ts(iso: Optional[str]) -> str:
    if not iso:
        return "—"
    try:
        dt = datetime.fromisoformat(iso)
        return dt.strftime("%Y-%m-%d %H:%M UTC")
    except Exception:
        return iso


def _now_ts() -> str:
    return datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC")


def build_incident_report_md(
    incident: Dict[str, Any],
    conversations: List[Dict[str, Any]],
    verdicts: List[Dict[str, Any]],
) -> str:
    """Markdown report. `conversations` are full conversation dicts (with
    `messages`); `verdicts` is the IOC verdict trail for those conversations."""
    inc = incident
    lines: List[str] = []
    lines.append(f"# {inc['case_number']} — {inc['title']}")
    lines.append("")
    lines.append(f"| Field | Value |")
    lines.append(f"|---|---|")
    lines.append(f"| Case | {inc['case_number']} |")
    lines.append(f"| Severity | {inc['severity'].upper()} |")
    lines.append(f"| Status | {inc['status']} |")
    lines.append(f"| Verdict | {inc.get('verdict') or '—'} |")
    lines.append(f"| Opened | {_fmt_ts(inc.get('created_at'))} |")
    lines.append(f"| Closed | {_fmt_ts(inc.get('closed_at'))} |")
    lines.append(f"| Report generated | {_now_ts()} |")
    lines.append("")

    if inc.get("notes"):
        lines.append("## Analyst Notes")
        lines.append("")
        lines.append(inc["notes"])
        lines.append("")

    if verdicts:
        lines.append("## IOC Verdicts")
        lines.append("")
        lines.append("| IOC | Type | Verdict | Confidence | Recorded |")
        lines.append("|---|---|---|---|---|")
        for v in verdicts:
            lines.append(
                f"| `{v['ioc_value']}` | {v['ioc_type']} | {v.get('verdict') or '—'} "
                f"| {v.get('confidence') or '—'} | {_fmt_ts(v.get('created_at'))} |"
            )
        lines.append("")

    lines.append("## Investigation Timeline")
    lines.append("")
    if not conversations:
        lines.append("_No conversations linked to this case._")
        lines.append("")
    for conv in conversations:
        lines.append(f"### {conv.get('title') or 'Untitled investigation'}")
        lines.append("")
        lines.append(f"_Started {_fmt_ts(conv.get('created_at'))}_")
        lines.append("")
        for m in conv.get("messages", []):
            who = "Analyst" if m["role"] == "user" else "NullShift"
            lines.append(f"**{who}** — {_fmt_ts(m.get('created_at'))}")
            lines.append("")
            content = m.get("content") or ""
            if not isinstance(content, str):
                content = str(content)
            lines.append(content)
            lines.append("")
            lines.append("---")
            lines.append("")

    lines.append(f"_Generated by NullShift on {_now_ts()}_")
    return "\n".join(lines)


