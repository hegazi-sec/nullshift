def build_incident_report_html(
    incident: Dict[str, Any],
    conversations: List[Dict[str, Any]],
    verdicts: List[Dict[str, Any]],
) -> str:
    inc = incident
    e = html.escape

    notes_html = ""
    if inc.get("notes"):
        notes_html = f"<h2>Analyst Notes</h2>\n<div class=\"notes\">{e(inc['notes'])}</div>"

    verdicts_html = ""
    if verdicts:
        rows = "\n".join(
            f"<tr><td class=\"mono\">{e(v['ioc_value'])}</td>"
            f"<td>{e(v['ioc_type'])}</td>"
            f"<td>{e(v.get('verdict') or '—')}</td>"
            f"<td>{e(v.get('confidence') or '—')}</td>"
            f"<td>{e(_fmt_ts(v.get('created_at')))}</td></tr>"
            for v in verdicts
        )
        verdicts_html = (
            "<h2>IOC Verdicts</h2>\n<table>"
            "<tr><th>IOC</th><th>Type</th><th>Verdict</th><th>Confidence</th><th>Recorded</th></tr>"
            f"{rows}</table>"
        )

    parts: List[str] = []
    if not conversations:
        parts.append('<p class="muted">No conversations linked to this case.</p>')
    for conv in conversations:
        parts.append(f"<h3>{e(conv.get('title') or 'Untitled investigation')}</h3>")
        parts.append(
            f'<p class="muted" style="margin:0 0 8px;font-size:12px">'
            f"Started {e(_fmt_ts(conv.get('created_at')))}</p>"
        )
        for m in conv.get("messages", []):
            role = m.get("role") or ""
            who = "Analyst" if role == "user" else "NullShift"
            cls = "assistant" if role != "user" else "user"
            content = m.get("content") or ""
            if not isinstance(content, str):
                content = str(content)
            parts.append(
                f'<div class="msg {cls}">'
                f'<div class="msg-head"><span>{who}</span>'
                f'<span class="ts">{e(_fmt_ts(m.get("created_at")))}</span></div>'
                f'<div class="msg-body">{e(content)}</div></div>'
            )
    timeline_html = "\n".join(parts)

    return _HTML_TEMPLATE.format(
        case_number=e(inc["case_number"]),
        title=e(inc["title"]),
        generated=e(_now_ts()),
        sev_color=_SEV_COLORS.get(inc["severity"], "#33415e"),
        severity=e(inc["severity"]),
        status=e(inc["status"]),
        verdict=e(inc.get("verdict") or "—"),
        opened=e(_fmt_ts(inc.get("created_at"))),
        closed=e(_fmt_ts(inc.get("closed_at"))),
        conv_count=len(conversations),
        notes_html=notes_html,
        verdicts_html=verdicts_html,
        timeline_html=timeline_html,
    )
